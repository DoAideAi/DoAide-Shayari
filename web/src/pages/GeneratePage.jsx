import { useState } from 'react';
import SEOHead from '../components/SEOHead';
import ContentCard from '../components/ContentCard';
import { generateMessage } from '../api/client';

const CATEGORIES = [
  { value: 'shayari', label: 'शायरी (Shayari)' },
  { value: 'good_morning', label: 'गुड मॉर्निंग (Good Morning)' },
  { value: 'good_night', label: 'गुड नाइट (Good Night)' },
  { value: 'love', label: 'लव कोट्स (Love Quotes)' },
  { value: 'birthday', label: 'बर्थडे विशेज (Birthday)' },
  { value: 'anniversary', label: 'एनिवर्सरी (Anniversary)' },
  { value: 'festival', label: 'त्योहार (Festival)' },
];

const SUBCATEGORIES = {
  shayari: [
    { value: 'love', label: 'लव / Love' },
    { value: 'sad', label: 'सैड / Sad' },
    { value: 'friendship', label: 'दोस्ती / Friendship' },
    { value: 'motivational', label: 'मोटिवेशनल / Motivational' },
    { value: 'attitude', label: 'एटीट्यूड / Attitude' },
    { value: 'funny', label: 'फ़नी / Funny' },
  ],
  festival: [
    { value: 'diwali', label: 'दिवाली / Diwali' },
    { value: 'holi', label: 'होली / Holi' },
    { value: 'eid', label: 'ईद / Eid' },
    { value: 'raksha_bandhan', label: 'रक्षाबंधन / Raksha Bandhan' },
    { value: 'navratri', label: 'नवरात्रि / Navratri' },
    { value: 'christmas', label: 'क्रिसमस / Christmas' },
    { value: 'new_year', label: 'नया साल / New Year' },
  ],
};

export default function GeneratePage() {
  const [category, setCategory] = useState('shayari');
  const [subcategory, setSubcategory] = useState('');
  const [context, setContext] = useState('');
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const subOptions = SUBCATEGORIES[category] || [];

  const handleGenerate = async () => {
    setLoading(true);
    setError('');
    setResult(null);
    try {
      const data = await generateMessage({
        category,
        subcategory: subcategory || undefined,
        context: context.trim() || undefined,
      });
      setResult(data);
    } catch (err) {
      setError(err.message || 'कुछ गलत हो गया। कृपया फिर से कोशिश करें।');
    } finally {
      setLoading(false);
    }
  };

  return (
    <>
      <SEOHead
        title="AI शायरी जनरेटर | AI Message Generator - DoAide Shayari"
        description="AI की मदद से अपनी पसंद की शायरी और शुभकामनाएं बनाएं। Personalized Hindi messages generated by AI."
        url="/generate"
        jsonLd={{ '@context': 'https://schema.org', '@type': 'WebApplication', name: 'AI Shayari Generator', description: 'AI शायरी जनरेटर — कैटेगरी चुनें, कस्टम शायरी और संदेश बनाएं', url: 'https://shayari.doaide.com/generate', applicationCategory: 'UtilityApplication', operatingSystem: 'Web', inLanguage: ['hi', 'en'], publisher: { '@type': 'Organization', name: 'DoAide | Shayari', url: 'https://shayari.doaide.com' } }}
      />

      <section className="bg-gradient-to-br from-primary-600 to-teal-400 text-white py-10 sm:py-14 px-4">
        <div className="max-w-3xl mx-auto text-center">
          <h1 className="text-2xl sm:text-3xl lg:text-4xl font-bold mb-2">
            <span className="font-hindi">✨ AI शायरी जनरेटर</span>
          </h1>
          <p className="text-base sm:text-lg opacity-90">AI से बनाएं अपनी ख़ास शायरी और शुभकामनाएं</p>
        </div>
      </section>

      <section className="max-w-xl mx-auto px-4 py-8">
        <div className="bg-[var(--da-bg)] rounded-2xl shadow-lg p-6 space-y-4 border border-[var(--da-border)]">
          <div>
            <label className="block text-sm font-medium text-[var(--da-text)] mb-1 font-hindi">कैटेगरी चुनें</label>
            <select
              value={category}
              onChange={(e) => { setCategory(e.target.value); setSubcategory(''); }}
              className="w-full px-4 py-2.5 rounded-xl border border-[var(--da-border)] bg-[var(--da-surface)] text-[var(--da-text)] focus:ring-2 focus:ring-primary-500 focus:border-transparent"
            >
              {CATEGORIES.map((c) => (
                <option key={c.value} value={c.value}>{c.label}</option>
              ))}
            </select>
          </div>

          {subOptions.length > 0 && (
            <div>
              <label className="block text-sm font-medium text-[var(--da-text)] mb-1 font-hindi">उपश्रेणी (ऑप्शनल)</label>
              <select
                value={subcategory}
                onChange={(e) => setSubcategory(e.target.value)}
                className="w-full px-4 py-2.5 rounded-xl border border-[var(--da-border)] bg-[var(--da-surface)] text-[var(--da-text)] focus:ring-2 focus:ring-primary-500 focus:border-transparent"
              >
                <option value="">— कोई भी —</option>
                {subOptions.map((s) => (
                  <option key={s.value} value={s.value}>{s.label}</option>
                ))}
              </select>
            </div>
          )}

          <div>
            <label className="block text-sm font-medium text-[var(--da-text)] mb-1 font-hindi">किसके लिए? (ऑप्शनल)</label>
            <input
              type="text"
              value={context}
              onChange={(e) => setContext(e.target.value)}
              placeholder="जैसे: बेस्ट फ्रेंड के लिए, पत्नी के लिए..."
              className="w-full px-4 py-2.5 rounded-xl border border-[var(--da-border)] bg-[var(--da-surface)] text-[var(--da-text)] placeholder-[var(--da-text-secondary)] focus:ring-2 focus:ring-primary-500 focus:border-transparent"
            />
          </div>

          <button
            onClick={handleGenerate}
            disabled={loading}
            className="w-full py-3 rounded-xl font-medium text-white bg-gradient-to-r from-primary-500 to-primary-600 hover:from-primary-600 hover:to-primary-700 disabled:opacity-50 disabled:cursor-not-allowed transition-all shadow-md"
          >
            {loading ? (
              <span className="inline-flex items-center gap-2">
                <svg className="animate-spin h-5 w-5" viewBox="0 0 24 24"><circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" fill="none"/><path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"/></svg>
                <span className="font-hindi">AI बना रहा है...</span>
              </span>
            ) : (
              <span className="font-hindi">✨ शायरी बनाएं</span>
            )}
          </button>

          {error && (
            <div className="p-3 rounded-xl bg-red-50 text-red-600 text-sm font-hindi">{error}</div>
          )}
        </div>

        {result && (
          <div className="mt-6">
            <ContentCard item={result} showLink={false} />
          </div>
        )}

        <p className="text-xs text-[var(--da-text-secondary)] text-center mt-4">
          प्रति मिनट 10 अनुरोध की सीमा है। Rate limit: 10 requests/minute.
        </p>
      </section>
    </>
  );
}
